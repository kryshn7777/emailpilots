import type { AiService } from './aiService';

/**
 * Reply classification (feature #2). Pure over an injected AiService — no direct
 * node-llama-cpp dependency — so it's testable with a stub and safe to import
 * anywhere. Classifies a single inbound reply into one of a fixed category set.
 */

export const REPLY_CATEGORIES = [
  'Interested',
  'Negative',
  'OutOfOffice',
  'Unsubscribe',
  'Bounce',
  'Referral',
  'MeetingBooked',
  'Other',
] as const;
export type ReplyCategory = typeof REPLY_CATEGORIES[number];

export interface ReplyClassification {
  category: ReplyCategory;
  confidence?: number;
}

/** Cap the body sent to the model to bound context + latency. */
const MAX_BODY_CHARS = 4000;

/**
 * These labels drive automations, and the automations are NOT symmetric — so the
 * prompt is written around which mistake costs more, not around neatness.
 *
 *  - `OutOfOffice` makes a drip CONTINUE (that is the whole point of pauseOnOoo in
 *    sequenceRunner). Every other reply stops it. So calling a real "no thanks" an
 *    auto-reply keeps emailing someone who declined — the worst outcome available
 *    here — while calling an auto-reply "Negative" merely stops a drip early. The
 *    prompt therefore makes OutOfOffice a HIGH bar: machine-generated or nothing.
 *  - `Unsubscribe` triggers auto-suppression. Missing one keeps mailing a person who
 *    asked you to stop (a CAN-SPAM problem); over-calling one costs an opportunity.
 *    So the prompt leans toward it when the intent is present at all.
 *
 * The examples are not padding: at temperature 0 with a JSON grammar, a 4B model
 * still needs the boundary cases drawn for it — a warm auto-reply reads as
 * "Interested" without them, and that is precisely the expensive mistake.
 */
const SYSTEM_PROMPT = `You classify ONE email reply into EXACTLY ONE category.

- Bounce: a delivery-failure notice from a mail system (mailer-daemon, postmaster, "undeliverable", "address not found").
- Unsubscribe: the person wants the emails to stop — "remove me", "unsubscribe", "stop contacting me", "take me off your list", or they say they have left the company and to stop writing.
- MeetingBooked: a specific meeting or call is agreed, proposed with a time, accepted, or confirmed.
- Referral: points you to a different person or team ("talk to Sarah", "forwarding to our CTO"), without agreeing to a meeting themselves.
- Interested: a human reply that wants to continue — asks a question, requests details, says yes or maybe.
- Negative: a human reply that declines, says no, is not interested, or is hostile.
- OutOfOffice: an AUTOMATIC away message generated by a mail system — vacation, parental leave, "I am currently out of the office", "this is an automated reply".
- Other: anything else, including replies you cannot place.

Rules, in order:
1. If a mail system generated it and it reports a delivery failure, it is Bounce — even if it also looks like an auto-reply.
2. If the person asks to stop being emailed, it is Unsubscribe — even if they are polite, even if they also decline, and even if it arrived as an auto-reply. When the intent to stop is present at all, choose Unsubscribe.
3. OutOfOffice requires a MACHINE-generated away message. If a human wrote it, it is never OutOfOffice, however away they say they are. "I'm slammed this week, try me next month" is a human reply, not an auto-reply. When unsure whether it is automatic, do NOT choose OutOfOffice.
4. A concrete time or an accepted invitation makes it MeetingBooked rather than Interested.
5. Naming someone else to contact makes it Referral rather than Interested.
6. Otherwise pick between Interested and Negative on what the person actually wants, not on how warm they sound. A polite no is Negative.
7. If none fit, Other. Never invent a category.

Examples:
Reply: "Automatic reply: I am out of the office until 5 May with limited access to email." -> {"category":"OutOfOffice","confidence":0.97}
Reply: "Thanks so much for reaching out! Unfortunately please remove me from your list." -> {"category":"Unsubscribe","confidence":0.95}
Reply: "I'm on leave right now but please stop sending me these." -> {"category":"Unsubscribe","confidence":0.9}
Reply: "Sounds good — Tuesday at 3pm works, I'll send an invite." -> {"category":"MeetingBooked","confidence":0.95}
Reply: "Not me, but Priya handles this — copying her in." -> {"category":"Referral","confidence":0.93}
Reply: "Interesting. What does pricing look like for a team of 20?" -> {"category":"Interested","confidence":0.92}
Reply: "Thanks, but we're happy with our current setup." -> {"category":"Negative","confidence":0.94}
Reply: "I'm travelling all month and won't get to this, sorry." -> {"category":"Negative","confidence":0.6}

confidence is your genuine certainty from 0 to 1. Use a low value when the reply is ambiguous — do not inflate it.
Respond with STRICT JSON ONLY: {"category":"<one category from the list>","confidence":<number 0..1>}. No prose, no code fences.`;

/**
 * Classify one reply. **Never throws** — returns `{category:'Other'}` on any model
 * or parse failure so the caller keeps recording the reply unaffected.
 */
export async function classifyReply(
  ai: AiService,
  input: { from?: string; subject?: string; body?: string }
): Promise<ReplyClassification> {
  const body = (input.body || '').slice(0, MAX_BODY_CHARS);
  const prompt = `From: ${input.from || '(unknown)'}\nSubject: ${input.subject || '(none)'}\n\n${body || '(no body)'}`;
  try {
    const res = await ai.generate({ prompt, system: SYSTEM_PROMPT, json: true, temperature: 0, maxTokens: 96 });
    const raw: any = res.json ?? safeParse(res.text);
    if (!raw || typeof raw !== 'object') return { category: 'Other' };
    const category = typeof raw.category === 'string' ? normalizeCategory(raw.category) : 'Other';
    const confidence = typeof raw.confidence === 'number' ? raw.confidence : undefined;
    return { category, confidence };
  } catch {
    return { category: 'Other' };
  }
}

function safeParse(text: string): any {
  try { return JSON.parse(text); } catch { return null; }
}

/** Map a loose model label onto a known category (case/space/punctuation-insensitive). */
export function normalizeCategory(s: string): ReplyCategory {
  const cleaned = String(s).trim().toLowerCase().replace(/[^a-z]/g, '');
  const match = REPLY_CATEGORIES.find(c => c.toLowerCase() === cleaned);
  return match || 'Other';
}
